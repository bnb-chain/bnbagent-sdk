"""The metric catalogue as Markdown (``bnbagent-eval metrics --markdown``, ``docs/METRICS.md``).

Generated from the registry, so the document always matches the installed metrics. The output
is deterministic: categories and aliases are sorted, methods keep their registry order (the
first method is the default). Only built-in metrics are listed by default; plugins and metrics
registered at run time (tests, notebooks) are left out.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence

from ..metrics import registry
from ..metrics.base import MethodSpec, MetricSpec
from ..metrics.vendors import PROVIDERS

__all__ = ["render_catalog", "render_third_party", "third_party_methods"]

_BUILTIN_PREFIX = "bnbagent_eval."
# Method kinds the eval service runs by default (``ServiceConfig.allowed_kinds``).
_DEFAULT_SERVICE_KINDS = ("rule", "judge")

_HEADER = """\
# Metric catalogue

<!-- Generated by `bnbagent-eval metrics --markdown`; do not edit by hand. -->

Every metric has a canonical ID `<category>.<name>` and one or more **methods**. A suite picks a
method with `method:`; without one, the first method listed is used.

- **Kind**: `rule` (deterministic code), `judge` (LLM-as-judge), `model` (our code running a
  local model) or `vendor` (a third-party evaluator; see "Third-party methods" below).
- **Extra**: the pip extra a method needs, e.g. `pip install 'bnbagent-eval[ragas]'`.
- **Required inputs**: `EvalCase` fields the method cannot run without (`tx` means the
  trajectory has transaction steps; `runs` means `options.runs` > 1 with a target). When
  methods differ, the inputs are listed per method.
- **Threshold**: the default pass threshold on the normalized [0, 1] score. `-` means none:
  set `threshold` in the suite, or, for the value metrics (`ops.latency`, `ops.cost`,
  `ops.token_usage`, `onchain.gas_efficiency`; spec `value_limits`), `value_target` /
  `value_max`. Other metrics ignore the value limits (`bnbagent-eval lint` warns).
- **Service**: whether the eval service (`bnbagent-eval serve`) may run the metric: `yes` (all
  methods), `no`, or the allowed methods. Methods marked `opt-in` (vendor and model kinds)
  run only when the operator enables their kind with `EVAL_SERVER_ALLOWED_KINDS`.
"""


def _is_builtin(spec: MetricSpec, method: MethodSpec | None = None) -> bool:
    try:
        cls, _ = registry.resolve(spec.id)
    except KeyError:
        return False
    if not cls.__module__.startswith(_BUILTIN_PREFIX):
        return False
    if method is None:
        return True
    handler = registry.method_handler(spec.id, method.name)
    return handler is None or getattr(handler, "__module__", "").startswith(_BUILTIN_PREFIX)


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _code(items: Iterable[str]) -> str:
    out = ", ".join(f"`{i}`" for i in items)
    return out or "-"


def _method_cell(m: MethodSpec) -> str:
    extra = f", `[{m.extra}]`" if m.extra else ""
    return f"`{m.name}` ({m.kind.value}{extra})"


def _inputs_cell(methods: Sequence[MethodSpec]) -> str:
    distinct = {m.required_inputs for m in methods}
    if len(distinct) == 1:
        return _code(sorted(methods[0].required_inputs))
    return "<br>".join(f"{m.name}: {_code(sorted(m.required_inputs))}" for m in methods)


def _service_cell(methods: Sequence[MethodSpec]) -> str:
    allowed = [m for m in methods if m.service_allowed]
    default = [m.name for m in allowed if m.kind.value in _DEFAULT_SERVICE_KINDS]
    opt_in = [m.name for m in allowed if m.kind.value not in _DEFAULT_SERVICE_KINDS]
    if not allowed:
        return "no"
    if len(default) == len(methods):
        return "yes"
    parts = [_code(default)] if default else []
    if opt_in:
        parts.append(f"opt-in: {_code(opt_in)}")
    return "<br>".join(parts)


def _threshold(value: float | None) -> str:
    return "-" if value is None else f"{value:g}"


def render_catalog(specs: Sequence[MetricSpec] | None = None, *, builtin_only: bool = True) -> str:
    """Markdown for ``specs`` (default: the registry): one table per category, then aliases."""
    if specs is None:
        specs = registry.list_specs()
    rows: list[tuple[MetricSpec, tuple[MethodSpec, ...]]] = []
    for spec in sorted(specs, key=lambda s: s.id):
        if builtin_only and not _is_builtin(spec):
            continue
        methods = tuple(m for m in spec.methods if not builtin_only or _is_builtin(spec, m))
        if methods:
            rows.append((spec, methods))
    by_category: dict[str, list[tuple[MetricSpec, tuple[MethodSpec, ...]]]] = {}
    for spec, methods in rows:
        by_category.setdefault(spec.category, []).append((spec, methods))

    lines = [_HEADER]
    n_methods = sum(len(m) for _, m in rows)
    lines.append(
        f"{len(rows)} metrics in {len(by_category)} categories, {n_methods} methods in total.\n"
    )
    lines.append("| Category | Metrics |")
    lines.append("|---|---|")
    for category, items in sorted(by_category.items()):
        lines.append(f"| [`{category}`](#{category}) | {len(items)} |")
    lines.append("")

    for category, items in sorted(by_category.items()):
        lines.append(f"## {category}\n")
        lines.append(
            "| ID | Description | Methods (kind, extra) | Required inputs | Threshold "
            "| Service | Sources |"
        )
        lines.append("|---|---|---|---|---|---|---|")
        for spec, methods in items:
            cells = [
                f"`{spec.id}`",
                _cell(spec.description),
                "<br>".join(_method_cell(m) for m in methods),
                _inputs_cell(methods),
                _threshold(spec.default_threshold),
                _service_cell(methods),
                _cell(", ".join(spec.sources)) or "-",
            ]
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")

    listed = {spec.id for spec, _ in rows}
    alias_rows = sorted(
        (alias, target, method)
        for alias, (target, method) in registry.aliases().items()
        if target in listed
    )
    lines.append(render_third_party(list(specs)))
    lines.append("## Aliases\n")
    lines.append(
        "An alias can be used as a metric `id` in a suite. It resolves to the canonical metric "
        "and, when a method is listed, selects that method. Results carry the canonical ID "
        "in `metric_id`.\n"
    )
    lines.append("| Alias | Metric | Method |")
    lines.append("|---|---|---|")
    for alias, target, method in alias_rows:
        lines.append(f"| `{alias}` | `{target}` | {f'`{method}`' if method else 'default'} |")
    return "\n".join(lines) + "\n"


def third_party_methods(
    specs: Sequence[MetricSpec] | None = None,
) -> dict[str, list[tuple[str, str]]]:
    """``{extra: [(metric_id, method), ...]}`` for every method backed by a third party."""
    out: dict[str, list[tuple[str, str]]] = {extra: [] for extra in PROVIDERS}
    for spec in specs if specs is not None else registry.list_specs():
        for m in spec.methods:
            if m.extra in PROVIDERS:
                out[m.extra].append((spec.id, m.name))
    return {k: sorted(v) for k, v in out.items() if v}


def render_third_party(specs: Sequence[MetricSpec] | None = None) -> str:
    """The "Third-party methods" section of the catalogue."""
    lines = [
        "## Third-party methods\n",
        "Optional methods whose score comes from another library or service (**evaluator**), "
        "or whose implementation is ours but runs a third-party model (**model**). Each installs "
        "with one command and is selected with `method:` like any other; the native method stays "
        "the default.\n",
        "| Provider | Role | Install | Needs | Methods |",
        "|---|---|---|---|---|",
    ]
    for extra, items in third_party_methods(specs).items():
        p = PROVIDERS[extra]
        methods = "<br>".join(f"`{metric}`: `{method}`" for metric, method in items)
        install = f"`pip install 'bnbagent-eval[{extra}]'`"
        lines.append(
            f"| [{p.name}]({p.url}) | {p.role} | {install} | {_cell(p.needs)} | {methods} |"
        )
    return "\n".join(lines) + "\n"
