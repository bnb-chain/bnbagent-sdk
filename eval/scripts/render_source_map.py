#!/usr/bin/env python3
"""Render the compact old → new map in docs/MAINTAINER_GUIDE.md from docs/design/source-map.md.

The design source map is the detailed one (source path:line, notes). The maintainer guide
carries a compact copy (source item → canonical ID + method → our file) between the markers
below; this script regenerates it so the two never drift.

    python3 eval/scripts/render_source_map.py           # rewrite the section
    python3 eval/scripts/render_source_map.py --check   # exit 1 if the guide is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parent.parent  # eval/
SOURCE_MAP = PACKAGE / "docs" / "design" / "source-map.md"
GUIDE = PACKAGE / "docs" / "MAINTAINER_GUIDE.md"
START = "<!-- source-map:start (generated by eval/scripts/render_source_map.py) -->"
END = "<!-- source-map:end -->"


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def source_tables(text: str) -> list[tuple[str, str, list[dict[str, str]]]]:
    """``(section, subsection, rows)`` for every table whose first column is a source path."""
    out: list[tuple[str, str, list[dict[str, str]]]] = []
    lines = text.splitlines()
    section = sub = label = ""
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("## "):
            section, sub, label = line[3:].strip(), "", ""
        elif line.startswith("### "):
            sub, label = line[4:].strip(), ""
        elif line.startswith("**") and line.count("**") >= 2:
            label = line.split("**")[1]  # e.g. "**RAGAS** (`RagasScorer`, 11 names)"
        if line.startswith("| Source") and i + 1 < len(lines) and lines[i + 1].startswith("|---"):
            header = _cells(line)
            rows = []
            i += 2
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(dict(zip(header, _cells(lines[i]), strict=False)))
                i += 1
            title = f"{sub.split(' ', 1)[0]} {label}" if label else sub  # "2.2 RAGAS"
            out.append((section, title, rows))
            continue
        i += 1
    return out


def _target(row: dict[str, str]) -> str:
    for key in ("Canonical ID", "Canonical ID / module", "Capability module"):
        if key in row:
            return row[key]
    return "–"


def render(text: str) -> str:
    parts = [START, ""]
    current_section = None
    for section, sub, rows in source_tables(text):
        if section != current_section:
            title = "ETK" if section.endswith("ETK") else section.split(". ", 1)[-1]
            parts += [f"#### {title}", ""]
            current_section = section
        parts += [f"**{sub}**" if sub else "", ""]
        parts += [
            "| Source item | New: canonical ID / module | Method | Our file |",
            "|---|---|---|---|",
        ]
        for row in rows:
            name = row.get("Source name", "")
            method = row.get("Method", "–") or "–"
            parts.append(f"| {name} | {_target(row)} | {method} | {row.get('Our file', '–')} |")
        parts.append("")
    parts.append(END)
    return "\n".join(p for i, p in enumerate(parts) if p or (i and parts[i - 1])) + "\n"


def updated_guide() -> tuple[str, str]:
    guide = GUIDE.read_text(encoding="utf-8")
    if START not in guide or END not in guide:
        sys.exit(f"{GUIDE}: markers not found")
    head, rest = guide.split(START, 1)
    _, tail = rest.split(END, 1)
    section = render(SOURCE_MAP.read_text(encoding="utf-8"))
    return guide, head + section.rstrip("\n") + tail


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    old, new = updated_guide()
    if args.check:
        if old != new:
            print(f"stale: {GUIDE.name} (run {Path(__file__).name})")
            return 1
        print(f"ok: {GUIDE.name} source map is up to date")
        return 0
    GUIDE.write_text(new, encoding="utf-8")
    print(f"wrote the source map section of {GUIDE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
